//! Byte-exact codec round trips, BOM policy behavior and typed failures for
//! the RFC-0006 §6.10 encoding matrix (AC-23).

#![allow(
    clippy::cast_possible_truncation,
    clippy::cast_lossless,
    clippy::doc_markdown,
    clippy::needless_range_loop
)]
use flavite_encoding::{
    CodecError, DecodeLimits, DecodePolicy, EncodeLimits, FileEncoding, SourceFormat,
    ascii_representable, decode, encode, encoded_len,
    stream::{Decoder, Encoder},
};

fn no_cancel() -> impl FnMut() -> bool {
    move || false
}

fn fixture(name: &str) -> Vec<u8> {
    let path = std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("tests/fixtures")
        .join(name);
    std::fs::read(&path).unwrap_or_else(|e| panic!("fixture {}: {e}", path.display()))
}

const RICH: &str = "A😀\r\nsecond\nthird\r\n";

fn expect_ok(name: &str, policy: DecodePolicy) -> flavite_encoding::DecodedContent {
    let bytes = fixture(name);
    decode(
        &bytes,
        policy,
        &DecodeLimits::default_envelope(),
        &mut no_cancel(),
    )
    .unwrap_or_else(|e| panic!("{name}: {e}"))
}

// ---- Golden independent constants (RFC-0006 §11) -------------------------

#[test]
fn golden_utf16le_and_be_bytes() {
    // Independently checked constants, not generated by the encoder under test.
    let le: Vec<u8> = vec![
        0xFF, 0xFE, 0x41, 0x00, 0x3D, 0xD8, 0x00, 0xDE, 0x0D, 0x00, 0x0A, 0x00,
    ];
    let be: Vec<u8> = vec![
        0xFE, 0xFF, 0x00, 0x41, 0xD8, 0x3D, 0xDE, 0x00, 0x00, 0x0D, 0x00, 0x0A,
    ];
    let out = encode(
        "A😀\r\n",
        &SourceFormat::utf16le_with_bom(),
        &EncodeLimits::default(),
        &mut no_cancel(),
    )
    .unwrap();
    assert_eq!(out, le);
    let out = encode(
        "A😀\r\n",
        &SourceFormat::utf16be_with_bom(),
        &EncodeLimits::default(),
        &mut no_cancel(),
    )
    .unwrap();
    assert_eq!(out, be);
    assert_eq!(
        decode(
            &le,
            DecodePolicy::Auto,
            &DecodeLimits::default(),
            &mut no_cancel()
        )
        .unwrap()
        .text(),
        "A😀\r\n"
    );
    assert_eq!(
        decode(
            &be,
            DecodePolicy::Auto,
            &DecodeLimits::default(),
            &mut no_cancel()
        )
        .unwrap()
        .text(),
        "A😀\r\n"
    );
}

// ---- Byte-exact round trips over the committed corpus --------------------

#[test]
fn round_trip_byte_exact_for_every_family() {
    struct Case {
        file: &'static str,
        policy: DecodePolicy,
        text: &'static str,
    }
    use DecodePolicy::Explicit as Ex;
    let cases = [
        Case {
            file: "empty.txt",
            policy: DecodePolicy::Auto,
            text: "",
        },
        Case {
            file: "ascii_plain.txt",
            policy: Ex(SourceFormat::ascii()),
            text: "Hello\r\nWorld\nplain ascii",
        },
        Case {
            file: "utf8_none.txt",
            policy: DecodePolicy::Auto,
            text: RICH,
        },
        Case {
            file: "utf8_bom.txt",
            policy: DecodePolicy::Auto,
            text: RICH,
        },
        Case {
            file: "utf8_bomonly.txt",
            policy: DecodePolicy::Auto,
            text: "",
        },
        Case {
            // The first EF BB BF is indistinguishable from a BOM under Auto;
            // Auto consumes it as the signature (documented ambiguity).
            file: "utf8_leadingfeff_none.txt",
            policy: DecodePolicy::Auto,
            text: RICH_1,
        },
        Case {
            // Explicit "no BOM" does NOT strip signature-shaped bytes: the
            // leading U+FEFF is content.
            file: "utf8_leadingfeff_none.txt",
            policy: Ex(SourceFormat::utf8()),
            text: "\u{FEFF}leading bom-shaped content\n",
        },
        Case {
            file: "utf16le_bom.txt",
            policy: DecodePolicy::Auto,
            text: RICH,
        },
        Case {
            file: "utf16le_none.txt",
            policy: Ex(SourceFormat::utf16le()),
            text: RICH,
        },
        Case {
            file: "utf16le_bomonly.txt",
            policy: DecodePolicy::Auto,
            text: "",
        },
        Case {
            file: "utf16le_leadingfeff_none.txt",
            policy: Ex(SourceFormat::utf16le()),
            text: "\u{FEFF}leading bom-shaped content\n",
        },
        Case {
            file: "utf16be_bom.txt",
            policy: DecodePolicy::Auto,
            text: RICH,
        },
        Case {
            file: "utf16be_none.txt",
            policy: Ex(SourceFormat::utf16be()),
            text: RICH,
        },
        Case {
            file: "utf16be_bomonly.txt",
            policy: DecodePolicy::Auto,
            text: "",
        },
    ];
    for case in cases {
        let d = expect_ok(case.file, case.policy);
        assert_eq!(d.text(), case.text, "{} text", case.file);
        let bytes = fixture(case.file);
        // encode(decode(bytes)) must reproduce the original bytes exactly.
        let out = encode(
            d.text(),
            &d.format(),
            &EncodeLimits::default(),
            &mut no_cancel(),
        )
        .unwrap_or_else(|e| panic!("{} re-encode: {e}", case.file));
        assert_eq!(out, bytes, "{} byte-exact round trip", case.file);
    }
}

const RICH_1: &str = "leading bom-shaped content\n";

#[test]
fn additional_bytes_under_explicit_no_bom_are_preserved_as_content() {
    // A U+FEFF in the middle of content must survive decode→encode verbatim.
    let text = "x\u{FEFF}y\r\n";
    for format in [
        SourceFormat::utf8(),
        SourceFormat::utf8_with_bom(),
        SourceFormat::utf16le(),
        SourceFormat::utf16le_with_bom(),
        SourceFormat::utf16be(),
        SourceFormat::utf16be_with_bom(),
    ] {
        let bytes = encode(text, &format, &EncodeLimits::default(), &mut no_cancel()).unwrap();
        let d = decode(
            &bytes,
            DecodePolicy::Explicit(format),
            &DecodeLimits::default(),
            &mut no_cancel(),
        )
        .unwrap();
        assert_eq!(d.text(), text);
        assert_eq!(d.format(), format);
    }
}

// ---- Auto policy semantics -----------------------------------------------

#[test]
fn auto_never_marks_ascii_and_accepts_utf8_bom_variants() {
    let d = expect_ok("ascii_plain.txt", DecodePolicy::Auto);
    assert_eq!(d.format().encoding(), FileEncoding::Utf8);
    assert!(!d.format().bom());
    let d = expect_ok("utf8_bom.txt", DecodePolicy::Auto);
    assert_eq!(d.format(), SourceFormat::utf8_with_bom());
    assert_eq!(d.map().bom_len(), 3);
    // FF FE prefix is checked as UTF-16LE BOM only when the 4-byte UTF-32
    // signature does not match; a longer unsupported signature errors first.
    let d = expect_ok("utf16le_bom.txt", DecodePolicy::Auto);
    assert_eq!(d.format(), SourceFormat::utf16le_with_bom());
}

#[test]
fn auto_rejects_utf32_signatures_before_utf16_prefixes() {
    for name in ["utf32le_bom_ambiguous.txt", "utf32be_bom_ambiguous.txt"] {
        let bytes = fixture(name);
        let err = decode(
            &bytes,
            DecodePolicy::Auto,
            &DecodeLimits::default_envelope(),
            &mut no_cancel(),
        )
        .expect_err(name);
        assert_eq!(err, CodecError::UnsupportedOrAmbiguousBom, "{name}");
    }
}

#[test]
fn explicit_utf16le_can_interpret_valid_leading_nul() {
    // The same bytes that Auto refuses (FF FE 00 00 …) decode under explicit
    // UTF-16LE with the leading NUL as real content.
    let bytes = fixture("utf32le_bom_ambiguous.txt");
    let d = decode(
        &bytes,
        DecodePolicy::Explicit(SourceFormat::utf16le_with_bom()),
        &DecodeLimits::default_envelope(),
        &mut no_cancel(),
    )
    .unwrap();
    assert!(d.text().starts_with('\u{0}'));
    assert!(d.text().contains('A'));
}

#[test]
fn explicit_bom_true_requires_exact_signature() {
    let bytes = fixture("utf8_none.txt"); // valid UTF-8, no BOM
    for format in [
        SourceFormat::utf8_with_bom(),
        SourceFormat::utf16le_with_bom(),
        SourceFormat::utf16be_with_bom(),
    ] {
        let err = decode(
            &bytes,
            DecodePolicy::Explicit(format),
            &DecodeLimits::default_envelope(),
            &mut no_cancel(),
        )
        .expect_err("must require the signature");
        assert_eq!(err, CodecError::BomConflict, "{format}");
    }
}

