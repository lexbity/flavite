// ---- Typed decode failures, with source positions ----------------------

#[test]
fn malformed_inputs_are_typed_and_located() {
    let bytes = fixture("utf8_invalid.txt");
    let err = decode(
        &bytes,
        DecodePolicy::Auto,
        &DecodeLimits::default_envelope(),
        &mut no_cancel(),
    )
    .unwrap_err();
    assert_eq!(err, CodecError::InvalidUtf8 { source_byte: 3 });

    let bytes = fixture("utf16le_odd_tail.txt");
    let err = decode(
        &bytes,
        DecodePolicy::Auto,
        &DecodeLimits::default_envelope(),
        &mut no_cancel(),
    )
    .unwrap_err();
    assert!(matches!(err, CodecError::OddUtf16ByteCount), "{err:?}");

    let bytes = fixture("utf16le_lone_high.txt");
    let err = decode(
        &bytes,
        DecodePolicy::Auto,
        &DecodeLimits::default_envelope(),
        &mut no_cancel(),
    )
    .unwrap_err();
    assert!(matches!(err, CodecError::InvalidUtf16 { .. }), "{err:?}");

    let bytes = fixture("utf16be_lone_low.txt");
    let err = decode(
        &bytes,
        DecodePolicy::Auto,
        &DecodeLimits::default_envelope(),
        &mut no_cancel(),
    )
    .unwrap_err();
    // A BOM-only prefix + a lone low surrogate errors at the low unit.
    assert_eq!(err, CodecError::InvalidUtf16 { source_byte: 2 });

    // Unpaired HIGH at EOF is reported at the high unit's position.
    let bytes: Vec<u8> = vec![0xFF, 0xFE, 0x00, 0xD8];
    let err = decode(
        &bytes,
        DecodePolicy::Auto,
        &DecodeLimits::default_envelope(),
        &mut no_cancel(),
    )
    .unwrap_err();
    assert_eq!(err, CodecError::InvalidUtf16 { source_byte: 2 });

    // Explicit strict ASCII against non-ASCII bytes is a located input error.
    let mut v = Vec::new();
    v.extend_from_slice(b"caf");
    v.extend_from_slice("é".as_bytes());
    let err = decode(
        &v,
        DecodePolicy::Explicit(SourceFormat::ascii()),
        &DecodeLimits::default_envelope(),
        &mut no_cancel(),
    )
    .unwrap_err();
    assert_eq!(err, CodecError::AsciiViolation { source_byte: 3 });
}

