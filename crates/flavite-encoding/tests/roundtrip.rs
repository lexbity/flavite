// ---- Strict ASCII output policy ----------------------------------------

#[test]
fn strict_ascii_save_fails_with_unencodable_before_any_effect() {
    let text = "fine\nthen 😀 appears";
    let byte = ascii_representable(text).unwrap();
    let start = usize::try_from(byte).unwrap();
    assert_eq!(&text.as_bytes()[start..start + 4], "😀".as_bytes());
    let err = encode(
        text,
        &SourceFormat::ascii(),
        &EncodeLimits::default_envelope(),
        &mut no_cancel(),
    )
    .unwrap_err();
    assert_eq!(err, CodecError::Unencodable { text_byte: byte });
    // encode() is pure: failure returned no bytes at all.
    assert_eq!(encoded_len(text, &SourceFormat::ascii()).unwrap_err(), err);
    // Pure-ASCII content succeeds with exact bytes.
    let out = encode(
        "abc\n",
        &SourceFormat::ascii(),
        &EncodeLimits::default_envelope(),
        &mut no_cancel(),
    )
    .unwrap();
    assert_eq!(out, b"abc\n");
}

// ---- Limits (NFR-19) ----------------------------------------------------

#[test]
fn limits_are_independent_and_checked() {
    let rich_le = fixture("utf16le_bom.txt");
    // Raw input bound.
    let tight_raw = DecodeLimits {
        max_raw_bytes: 8,
        ..DecodeLimits::default_envelope()
    };
    let err = decode(&rich_le, DecodePolicy::Auto, &tight_raw, &mut no_cancel()).unwrap_err();
    assert!(matches!(
        err,
        CodecError::LimitExceeded {
            kind: flavite_encoding::CodecLimitKind::RawInput,
            ..
        }
    ));
    // Decoded UTF-8 bound: UTF-16 BMP expands when decoded to UTF-8, so the
    // raw bound is NOT a substitute.
    let tight_decoded = DecodeLimits {
        max_raw_bytes: 1 << 20,
        max_decoded_utf8_bytes: 4,
        max_map_bytes: 1 << 20,
    };
    let err = decode(
        &rich_le,
        DecodePolicy::Auto,
        &tight_decoded,
        &mut no_cancel(),
    )
    .unwrap_err();
    assert!(matches!(
        err,
        CodecError::LimitExceeded {
            kind: flavite_encoding::CodecLimitKind::DecodedUtf8,
            ..
        }
    ));
    // ASCII expands when saved as UTF-16: output bound is independent.
    let enc_limits = EncodeLimits {
        max_input_utf8_bytes: 1 << 20,
        max_output_bytes: 4,
    };
    let err = encode(
        "12345",
        &SourceFormat::utf16le(),
        &enc_limits,
        &mut no_cancel(),
    )
    .unwrap_err();
    assert!(matches!(
        err,
        CodecError::LimitExceeded {
            kind: flavite_encoding::CodecLimitKind::EncodeOutput,
            ..
        }
    ));
    // Map bound trips on large UTF-16 with a tiny map allowance.
    let many = "a".repeat(255 * 100);
    let le_bytes = encode(
        &many,
        &SourceFormat::utf16le(),
        &EncodeLimits::default_envelope(),
        &mut no_cancel(),
    )
    .unwrap();
    let tight_map = DecodeLimits {
        max_raw_bytes: 1 << 24,
        max_decoded_utf8_bytes: 1 << 24,
        max_map_bytes: 8,
    };
    let err = decode(
        &le_bytes,
        DecodePolicy::Explicit(SourceFormat::utf16le()),
        &tight_map,
        &mut no_cancel(),
    )
    .unwrap_err();
    assert!(matches!(
        err,
        CodecError::LimitExceeded {
            kind: flavite_encoding::CodecLimitKind::MapBytes,
            ..
        }
    ));
}

#[test]
fn cancellation_is_honored_at_progress_points() {
    let big = "x".repeat(200_000);
    let le = encode(
        &big,
        &SourceFormat::utf16le(),
        &EncodeLimits::default_envelope(),
        &mut no_cancel(),
    )
    .unwrap();
    let mut flag = false;
    let err = decode(
        &le,
        DecodePolicy::Explicit(SourceFormat::utf16le()),
        &DecodeLimits::default_envelope(),
        &mut || {
            let now = flag;
            flag = true; // cancel after the first check
            now
        },
    )
    .unwrap_err();
    // First check at offset 0 is skipped (progress guard) — the cancel fires
    // either mid-stream or at finish.
    assert!(matches!(err, CodecError::Cancelled), "{err:?}");
}

// ---- Streaming equals whole-buffer at every split point (NFR-18/§6.10) --

#[test]
fn streaming_matches_whole_buffer_for_every_split() {
    use DecodePolicy::Explicit as Ex;
    // (fixture, policy) pairs spanning UTF-8/16, BOMs, leading FEFF intent
    // and malformed inputs: whatever the whole-buffer path produces (text or
    // typed error), byte-split streaming must produce identically.
    let cases: &[(&str, DecodePolicy)] = &[
        ("ascii_plain.txt", DecodePolicy::Auto),
        ("utf8_bom.txt", DecodePolicy::Auto),
        ("utf16le_bom.txt", DecodePolicy::Auto),
        ("utf16be_none.txt", Ex(SourceFormat::utf16be())),
        ("utf16le_none.txt", Ex(SourceFormat::utf16le())),
        ("utf16le_leadingfeff_none.txt", Ex(SourceFormat::utf16le())),
        ("utf8_leadingfeff_none.txt", Ex(SourceFormat::utf8())),
        ("utf16le_odd_tail.txt", DecodePolicy::Auto),
        ("utf16le_lone_high.txt", DecodePolicy::Auto),
        ("utf8_invalid.txt", DecodePolicy::Auto),
        ("utf32le_bom_ambiguous.txt", DecodePolicy::Auto),
        ("empty.txt", DecodePolicy::Auto),
    ];
    for (name, policy) in cases {
        let bytes = fixture(name);
        let whole = decode(
            &bytes,
            *policy,
            &DecodeLimits::default_envelope(),
            &mut no_cancel(),
        );
        for split in 0..=bytes.len() {
            let mut decoder = Decoder::new(*policy, DecodeLimits::default_envelope());
            let mut sink = String::new();
            let mut outcome = Ok(());
            if let Err(e) = decoder.feed(&bytes[..split], &mut sink) {
                outcome = Err(e);
            } else if let Err(e) = decoder.feed(&bytes[split..], &mut sink) {
                outcome = Err(e);
            } else if let Err(e) = decoder.finish(&mut sink) {
                outcome = Err(e);
            }
            match (&whole, &outcome) {
                (Ok(w), Ok(())) => {
                    assert_eq!(sink, w.text(), "{name} split {split}");
                    assert_eq!(
                        w.format().encoding(),
                        decoder.resolved_encoding().unwrap_or(w.format().encoding())
                    );
                }
                (Err(we), Err(se)) => {
                    // Error kind must match; positions may differ only where
                    // chunking legitimately delays detection — compare kinds.
                    assert_eq!(
                        std::mem::discriminant(we),
                        std::mem::discriminant(se),
                        "{name} split {split}: whole {we:?} vs stream {se:?}"
                    );
                }
                (other_whole, other_stream) => {
                    panic!("{name} split {split}: whole {other_whole:?} vs stream {other_stream:?}")
                }
            }
        }
    }
}

#[test]
fn streaming_reports_incomplete_suffix_only_at_finish() {
    // A UTF-16LE BOM plus a split code unit: no error at feed, Odd at finish.
    let mut decoder = Decoder::new(DecodePolicy::Auto, DecodeLimits::default_envelope());
    let mut sink = String::new();
    decoder.feed(b"\xff\xfeA", &mut sink).unwrap();
    let err = decoder.finish(&mut sink).unwrap_err();
    assert!(matches!(err, CodecError::OddUtf16ByteCount), "{err:?}");
    // And a split surrogate pair completes fine across feeds.
    let mut decoder = Decoder::new(
        DecodePolicy::Explicit(SourceFormat::utf16le()),
        DecodeLimits::default_envelope(),
    );
    let mut sink = String::new();
    decoder.feed(&[0x3D, 0xD8, 0x00], &mut sink).unwrap(); // high + half of low
    decoder.feed(&[0xDE], &mut sink).unwrap();
    let meta = decoder.finish(&mut sink).unwrap();
    assert_eq!(sink, "😀");
    assert_eq!(meta.decoded_len, 4);
}

#[test]
fn streaming_encoder_matches_whole_encode() {
    let text = "mixed content: é😀\r\nend";
    for format in [
        SourceFormat::utf8(),
        SourceFormat::utf8_with_bom(),
        SourceFormat::ascii(),
        SourceFormat::utf16le_with_bom(),
        SourceFormat::utf16be(),
    ] {
        let whole = encode(
            text,
            &format,
            &EncodeLimits::default_envelope(),
            &mut no_cancel(),
        );
        let ascii_policy = format.encoding() == FileEncoding::Ascii;
        if ascii_policy {
            assert!(whole.is_err(), "non-ascii text must reject ASCII");
            continue;
        }
        let whole = whole.unwrap();
        let mut out = Vec::new();
        let mut enc = Encoder::new(format, EncodeLimits::default_envelope());
        out.extend_from_slice(enc.header());
        // Split at every char boundary.
        for split in 0..=text.chars().count() {
            out.clear();
            out.extend_from_slice(enc.header());
            let head: String = text.chars().take(split).collect();
            let tail: String = text.chars().skip(split).collect();
            enc.encode(&head, &mut out).unwrap();
            enc.encode(&tail, &mut out).unwrap();
            assert_eq!(out, whole, "split {split} at {format}");
        }
    }
}
